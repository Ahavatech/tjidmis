def soup(path):
    return BeautifulSoup(open(path, encoding='utf-8').read(), 'html.parser')


def tok(s):
    s = s.replace(JURL, '__JURL__').replace('https://jidmis.org/public/', '__PUBLIC__/').replace('https://jidmis.org/templates/images/', '__ASSETS__/img/')
    s = s.replace('//jidmis.org/public/', '__PUBLIC__/')
    return s


def inner(el, drop=()):
    if el is None:
        return ''
    el = BeautifulSoup(str(el), 'html.parser').find()
    for sel in drop:
        for x in el.select(sel):
            x.decompose()
    return tok(''.join(str(c) for c in el.contents)).strip()


def q(v):
    if v is None:
        return 'NULL'
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''") + "'"


def text(el):
    return re.sub(r'\s+', ' ', el.get_text(' ', strip=True)) if el else ''


